// Lesson 03
// Learning Operators
// Operators are symbols that perform operations in programming
int monthlySalary = 15000;
int rent = 3500;
int transport = 2000;
int annualSalary = monthlySalary * 12;

int remainingSalary = monthlySalary -  rent -  transport;

Console.WriteLine("Salary: " + monthlySalary);
Console.WriteLine("Rent: " + rent);
Console.WriteLine("Transport: " + transport);
Console.WriteLine("Remaining: " + remainingSalary);
Console.WriteLine("Annual Salary: " + annualSalary);
